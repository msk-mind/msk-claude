#!/usr/bin/env python3
"""aiportal - manage the MSK AI Portal proxy for opencode and Claude Code.

Usage:
  aiportal proxy start          Run the proxy in the foreground (to watch its output)
  aiportal proxy stop           Stop this machine's background proxy
  aiportal proxy status         Show where the proxy is running and whether it answers
  aiportal proxy logs           Follow this machine's proxy log
  aiportal models               List the configured models
  aiportal models sync [--apply] [--test]
                                Compare the config with the models the MSK endpoint
                                offers. --apply adds new models, removes retired ones,
                                refreshes token limits and the README model list.
                                --test sends a one-line prompt to every configured model.
  aiportal token                Check the session token in .auth.env

proxy/litellm_config.yaml is the single source of truth for the model list; the
launch commands, the opencode config and the README list are generated from it.
"""
import base64
import json
import os
import re
import secrets
import signal
import socket
import stat
import sys
import tempfile
import time

REPO_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIG_PATH = os.path.join(REPO_DIR, "proxy", "litellm_config.yaml")
RUN_PROXY = os.path.join(REPO_DIR, "proxy", "run.sh")
AUTH_PATH = os.path.join(REPO_DIR, ".auth.env")
README_PATH = os.path.join(REPO_DIR, "README.md")

# Runtime state: the shared proxy key, plus one directory per machine
STATE_ROOT = os.path.join(REPO_DIR, ".proxy")
PROXY_KEY_PATH = os.path.join(STATE_ROOT, "master_key")
LEGACY_KEY_PATH = os.path.join(REPO_DIR, ".litellm_master_key")


def host_state_dir(host=None):
    return os.path.join(STATE_ROOT, host or socket.gethostname())

WEBUI_URL = "https://chat.aicopilot.aws.mskcc.org"
API_BASE = f"{WEBUI_URL}/api/v1"

# Endpoint entries that are routers rather than models
EXCLUDED_ENDPOINT_IDS = {"msk-default"}

TOKEN_WARN_DAYS = 2

README_BEGIN = "<!-- BEGIN MODEL LIST (generated by aiportal models sync) -->"
README_END = "<!-- END MODEL LIST -->"

TOKEN_HELP = f"""To get a new token:
  1. Visit {WEBUI_URL} and log in
  2. Open Developer Tools (F12; Cmd+Option+I on a Mac)
  3. Go to the cookies for that site:
       Chrome/Edge: Application tab -> Cookies;  Firefox/Safari: Storage tab -> Cookies
  4. Copy the value of the 'token' cookie
  5. Put it in {AUTH_PATH}:
       export WEBUI_SESSION_TOKEN='<token>'"""


# --- config -----------------------------------------------------------------

def _yaml():
    from ruamel.yaml import YAML
    y = YAML()
    y.preserve_quotes = True
    y.width = 200
    y.indent(mapping=2, sequence=4, offset=2)
    return y


def load_config():
    with open(CONFIG_PATH) as f:
        return _yaml().load(f)


def _space_model_entries(text):
    """Put a blank line between model_list entries."""
    return re.sub(r"\n+(  - model_name:)", r"\n\n\1", text).replace("model_list:\n\n", "model_list:\n")


def _clear_comments(node):
    if hasattr(node, "ca"):
        node.ca.items.clear()
        node.ca.comment = None
    children = node.values() if isinstance(node, dict) else node if isinstance(node, list) else []
    for child in children:
        _clear_comments(child)


def save_config(config):
    # model_list carries no comments; clearing them stops blank separator lines
    # (which ruamel stores as comments) from drifting when keys are added
    _clear_comments(config["model_list"])
    with open(CONFIG_PATH, "w") as f:
        _yaml().dump(config, f, transform=_space_model_entries)


def backend_id(entry):
    """The model id on the MSK endpoint, e.g. bedrock/us.anthropic.claude-opus-5."""
    return entry["litellm_params"]["model"].removeprefix("openai/")


def visible_models(config):
    return [m for m in config["model_list"] if not m.get("model_info", {}).get("hidden")]


def group_of(name):
    if name.startswith("claude-"):
        return "Claude Models"
    if name.startswith(("gpt-", "o1", "o3", "o4")):
        return "OpenAI GPT Models (via Azure)"
    return "Other Models"


# --- token ------------------------------------------------------------------

def load_token():
    """The token in .auth.env wins over the environment, so refreshing the file always takes effect."""
    if os.path.exists(AUTH_PATH):
        m = re.search(r"WEBUI_SESSION_TOKEN=['\"]?([^'\"\n]+)", open(AUTH_PATH).read())
        if m:
            return m.group(1)
    return os.environ.get("WEBUI_SESSION_TOKEN")


def token_expiry(token):
    try:
        payload = token.split(".")[1]
        payload += "=" * (-len(payload) % 4)
        return json.loads(base64.urlsafe_b64decode(payload)).get("exp")
    except Exception:
        return None


def restrict_to_owner(path):
    """Make a secret file readable only by its owner; returns True if it had to be tightened."""
    mode = stat.S_IMODE(os.stat(path).st_mode)
    if mode & (stat.S_IRWXG | stat.S_IRWXO):
        os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)
        return True
    return False


def _new_key_file():
    """Write a fresh key to a private temp file next to the key file and return its path."""
    fd, tmp = tempfile.mkstemp(prefix="master_key.", suffix=".tmp", dir=STATE_ROOT)
    with os.fdopen(fd, "w") as f:
        f.write(f"sk-{secrets.token_urlsafe(32)}\n")
    return tmp


def _read_key():
    try:
        return open(PROXY_KEY_PATH).read().strip()
    except FileNotFoundError:
        return ""


def ensure_proxy_key():
    """The secret clients use to authenticate to the proxy, created on first use.

    The key file only ever appears fully written: it is created by hard-linking a
    complete temp file into place, which also fails safely if another process
    created it first. An empty or truncated key is replaced, never returned.
    """
    os.makedirs(STATE_ROOT, mode=0o700, exist_ok=True)
    if os.path.exists(LEGACY_KEY_PATH) and not os.path.exists(PROXY_KEY_PATH):
        os.replace(LEGACY_KEY_PATH, PROXY_KEY_PATH)
    if not os.path.exists(PROXY_KEY_PATH):
        tmp = _new_key_file()
        try:
            os.link(tmp, PROXY_KEY_PATH)
        except FileExistsError:
            pass
        finally:
            os.unlink(tmp)
    key = _read_key()
    if len(key) < 20:
        tmp = _new_key_file()
        os.replace(tmp, PROXY_KEY_PATH)
        key = _read_key()
    restrict_to_owner(PROXY_KEY_PATH)
    return key


def cmd_token_check():
    """Exit 0 if usable (possibly with a warning), 1 if missing or expired."""
    if os.path.exists(AUTH_PATH) and restrict_to_owner(AUTH_PATH):
        print(f"Note: {AUTH_PATH} was readable by other users; restricted it to you.")
    token = load_token()
    if not token:
        print(f"Error: WEBUI_SESSION_TOKEN not found in {AUTH_PATH}\n\n{TOKEN_HELP}")
        return 1
    exp = token_expiry(token)
    if exp is None:
        return 0
    remaining = exp - time.time()
    when = time.strftime("%Y-%m-%d %H:%M", time.localtime(exp))
    if remaining <= 0:
        print(f"Error: your MSK session token expired on {when}.\n\n{TOKEN_HELP}")
        return 1
    if remaining < TOKEN_WARN_DAYS * 86400:
        hours = round(remaining / 3600)
        print(f"Warning: your MSK session token expires in {hours}h ({when}).\n\n{TOKEN_HELP}\n")
    return 0


# --- endpoint ---------------------------------------------------------------

def _session():
    import requests
    import urllib3
    urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)
    s = requests.Session()
    s.verify = False
    s.headers["Authorization"] = f"Bearer {load_token()}"
    return s


def endpoint_models():
    """Real models on the endpoint, skipping assistant presets, pipes and routers."""
    r = _session().get(f"{API_BASE}/models", timeout=30)
    r.raise_for_status()
    models = {}
    for m in r.json()["data"]:
        info = m.get("info") or {}
        if "pipe" in m or info.get("base_model_id") or m["id"] in EXCLUDED_ENDPOINT_IDS:
            continue
        models[m["id"]] = m
    return models


def smoke_test(model_id):
    r = _session().post(
        f"{API_BASE}/chat/completions",
        json={
            "model": model_id,
            "messages": [{"role": "user", "content": "Reply with OK"}],
            "max_tokens": 1000,
            "chat_id": "",
        },
        timeout=180,
    )
    if r.ok:
        return True, ""
    return False, f"{r.status_code} {r.text[:120]}"


def friendly_name(endpoint_model):
    """'OpenAI GPT-5.6 Terra' -> 'gpt-5.6-terra', 'Claude Opus 5.5' -> 'claude-opus-5.5'."""
    name = re.sub(r"^OpenAI\s+", "", endpoint_model.get("name") or endpoint_model["id"])
    return re.sub(r"\s+", "-", name.strip()).lower()


def display_name(endpoint_model):
    return re.sub(r"^OpenAI\s+", "", endpoint_model.get("name") or endpoint_model["id"])


def new_entry(endpoint_model):
    from ruamel.yaml.comments import CommentedMap
    is_claude = "anthropic.claude" in endpoint_model["id"]
    params = CommentedMap(
        model=f"openai/{endpoint_model['id']}",
        api_base=API_BASE,
        api_key="os.environ/WEBUI_SESSION_TOKEN",
    )
    if is_claude:
        params["drop_params"] = True
        params["max_tokens"] = 16384
    info = CommentedMap(verify_ssl=False, display_name=display_name(endpoint_model))
    info["max_input_tokens"] = endpoint_model.get("max_input_tokens") or 128000
    info["max_output_tokens"] = endpoint_model.get("max_output_tokens") or 32768
    return CommentedMap(model_name=friendly_name(endpoint_model), litellm_params=params, model_info=info)


def remove_from_fallbacks(config, names):
    router = config.get("router_settings", {})
    for key in ("fallbacks", "content_policy_fallbacks"):
        rules = router.get(key) or []
        for rule in list(rules):
            (primary, targets), = rule.items()
            if primary in names:
                rules.remove(rule)
                continue
            for t in [t for t in targets if t in names]:
                targets.remove(t)
            if not targets:
                rules.remove(rule)


def cmd_sync(apply, test):
    config = load_config()
    live = endpoint_models()
    entries = config["model_list"]
    configured = {backend_id(m) for m in entries}

    added = [mid for mid in live if mid not in configured]
    retired = [m["model_name"] for m in entries if backend_id(m) not in live]
    changed_limits = []
    for entry in entries:
        mid = backend_id(entry)
        if mid not in live:
            continue
        info = entry.setdefault("model_info", {})
        for key in ("max_input_tokens", "max_output_tokens"):
            value = live[mid].get(key)
            if value and info.get(key) != value:
                changed_limits.append(f"{entry['model_name']}: {key} {info.get(key)} -> {value}")
                info[key] = value

    print(f"Endpoint offers {len(live)} models; config has {len(entries)} entries.")
    for mid in added:
        print(f"  + new:     {friendly_name(live[mid])}  ({mid})")
    for name in retired:
        print(f"  - retired: {name}")
    for line in changed_limits:
        print(f"  ~ limits:  {line}")
    if not (added or retired or changed_limits):
        print("  Config is up to date.")

    if apply and (added or retired or changed_limits):
        for name in retired:
            config["model_list"] = [m for m in config["model_list"] if m["model_name"] != name]
        remove_from_fallbacks(config, set(retired))
        for mid in added:
            config["model_list"].append(new_entry(live[mid]))
        save_config(config)
        write_readme(config)
        print(f"\nUpdated {CONFIG_PATH} and {README_PATH}.")
        print("The proxy restarts automatically on your next aiportal-opencode / aiportal-claude launch.")
        if retired:
            print("If a retired model was a DEFAULT_MODEL, update it in bin/aiportal-opencode / bin/aiportal-claude.")
    elif added or retired or changed_limits:
        print("\nRun 'aiportal models sync --apply' to update the config.")

    if test:
        print("\nTesting configured models against the endpoint:")
        failed = 0
        for entry in load_config()["model_list"] if apply else config["model_list"]:
            if entry.get("model_info", {}).get("hidden"):
                continue
            ok, err = smoke_test(backend_id(entry))
            failed += not ok
            print(f"  {'OK  ' if ok else 'FAIL'} {entry['model_name']}  {err}")
        return 1 if failed else 0
    return 0


# --- generated outputs --------------------------------------------------------

def cmd_names():
    for m in visible_models(load_config()):
        print(m["model_name"])


def cmd_opencode_models():
    models = {}
    for m in visible_models(load_config()):
        info = m.get("model_info", {})
        entry = {
            "name": info.get("display_name", m["model_name"]),
            "tool_call": info.get("supports_function_calling", True),
            "attachment": info.get("supports_vision", True),
        }
        if info.get("max_input_tokens") and info.get("max_output_tokens"):
            entry["limit"] = {"context": info["max_input_tokens"], "output": info["max_output_tokens"]}
        models[m["model_name"]] = entry
    print(json.dumps(models))


def readme_section(config):
    lines = []
    groups = {}
    for m in visible_models(config):
        groups.setdefault(group_of(m["model_name"]), []).append(m)
    for group in ("Claude Models", "OpenAI GPT Models (via Azure)", "Other Models"):
        if group not in groups:
            continue
        lines.append(f"**{group}:**")
        for m in groups[group]:
            info = m.get("model_info", {})
            ctx = info.get("max_input_tokens")
            out = info.get("max_output_tokens")
            limits = f" - {ctx:,} context / {out:,} max output" if ctx and out else ""
            lines.append(f"- `{m['model_name']}` - {info.get('display_name', m['model_name'])}{limits}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_readme(config):
    text = open(README_PATH).read()
    if README_BEGIN not in text:
        return
    start = text.index(README_BEGIN) + len(README_BEGIN)
    end = text.index(README_END)
    text = text[:start] + "\n" + readme_section(config) + text[end:]
    with open(README_PATH, "w") as f:
        f.write(text)


# --- proxy --------------------------------------------------------------------

def read_server_info(path):
    info = {}
    try:
        for line in open(path):
            key, _, value = line.strip().partition("=")
            info[key] = value
    except FileNotFoundError:
        return None
    return info


def probe(host, port):
    """'ok' if the proxy accepts our key, 'rejected' if it doesn't, 'down' if unreachable."""
    import requests
    try:
        r = requests.get(f"http://{host}:{port}/v1/models", timeout=5,
                         headers={"Authorization": f"Bearer {ensure_proxy_key()}"},
                         proxies={"http": None, "https": None})
    except requests.RequestException:
        return "down"
    return "ok" if r.status_code == 200 else "rejected" if r.status_code in (400, 401, 403) else "down"


def owned_pid(state_dir):
    """The pid of this machine's background proxy, if one is recorded and alive."""
    try:
        host, pid = open(os.path.join(state_dir, "proxy.pid")).read().split()
        pid = int(pid)
        if host != socket.gethostname():
            return None
        os.kill(pid, 0)
        return pid
    except (FileNotFoundError, ValueError, ProcessLookupError, PermissionError):
        return None


def cmd_proxy_stop():
    state_dir = host_state_dir()
    pid = owned_pid(state_dir)
    if pid is None:
        print(f"No background proxy running on {socket.gethostname()}")
    else:
        # The proxy runs in its own session, so its pid is also its process group id
        try:
            os.killpg(pid, signal.SIGTERM)
        except ProcessLookupError:
            os.kill(pid, signal.SIGTERM)
        print(f"Stopped the proxy (pid {pid})")
    for name in ("proxy.pid", "server_info"):
        try:
            os.unlink(os.path.join(state_dir, name))
        except FileNotFoundError:
            pass
    return 0


def cmd_proxy_status():
    here = socket.gethostname()
    found = False
    hosts = sorted(os.listdir(STATE_ROOT)) if os.path.isdir(STATE_ROOT) else []
    for host in hosts:
        if not os.path.isdir(os.path.join(STATE_ROOT, host)):
            continue
        info = read_server_info(os.path.join(STATE_ROOT, host, "server_info"))
        if not info:
            continue
        found = True
        local_only = info.get("bind") == "127.0.0.1"
        if host == here:
            addr = "127.0.0.1" if local_only else info.get("hostname", host)
            state = probe(addr, info.get("port"))
            pid = owned_pid(host_state_dir(host))
            started = f"background, pid {pid}" if pid else "foreground or not started by aiportal"
            print(f"{host} (this machine): {state} at http://{addr}:{info.get('port')} ({started})")
            print(f"  listening on {info.get('bind', '?')}; log: {os.path.join(STATE_ROOT, host, 'proxy.log')}")
        elif local_only:
            print(f"{host}: localhost-only proxy on port {info.get('port')} (not reachable from {here})")
        else:
            state = probe(info.get("hostname", host), info.get("port"))
            print(f"{host}: shared proxy, {state} at http://{info.get('hostname', host)}:{info.get('port')}")
    if not found:
        print("No proxy recorded. aiportal-opencode / aiportal-claude start one automatically.")
    return 0


def cmd_proxy_logs():
    log = os.path.join(host_state_dir(), "proxy.log")
    if not os.path.exists(log):
        print(f"No proxy log on {socket.gethostname()} ({log})")
        return 1
    os.execvp("tail", ["tail", "-n", "50", "-f", log])


def cmd_proxy_start():
    """Run the proxy in the foreground on this machine."""
    if cmd_token_check():
        return 1
    if owned_pid(host_state_dir()):
        print("A background proxy is already running on this machine; stop it first with 'aiportal proxy stop'.")
        return 1
    os.execv(RUN_PROXY, [RUN_PROXY])


def main(argv):
    if not argv or argv[0] in ("-h", "--help", "help"):
        print(__doc__)
        return 0
    cmd, args = argv[0], argv[1:]
    sub = args[0] if args else None

    # User-facing commands
    if cmd == "proxy" and sub in ("start", "stop", "status", "logs"):
        return {"start": cmd_proxy_start, "stop": cmd_proxy_stop,
                "status": cmd_proxy_status, "logs": cmd_proxy_logs}[sub]()
    if cmd == "models" and sub is None:
        cmd_names()
        return 0
    if cmd == "models" and sub == "sync":
        return cmd_sync(apply="--apply" in args, test="--test" in args)
    if cmd == "token":
        rc = cmd_token_check()
        if rc == 0:
            exp = token_expiry(load_token() or "")
            if exp:
                print(f"Token is valid until {time.strftime('%Y-%m-%d %H:%M', time.localtime(exp))}.")
        return rc

    # Internal commands used by the launch scripts
    if cmd == "_token-check":
        return cmd_token_check()
    if cmd == "_proxy-key":
        print(ensure_proxy_key())
        return 0
    if cmd == "_opencode-models":
        cmd_opencode_models()
        return 0
    if cmd == "_readme":
        write_readme(load_config())
        return 0

    print(f"Unknown command: {' '.join(argv)}\n{__doc__}")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
