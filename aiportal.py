#!/usr/bin/env python3
"""
Helper for the MSK LiteLLM proxy scripts. litellm_config.yaml is the single
source of truth for the model list; everything else is generated from it.

Usage:
  aiportal.py names                 Print user-facing model names, one per line
  aiportal.py opencode-models       Print the opencode provider "models" block as JSON
  aiportal.py token-check           Check the session token in .auth.env for expiry
  aiportal.py proxy-key             Print the proxy's secret key, creating it on first use
  aiportal.py sync [--apply] [--test]
                               Compare litellm_config.yaml with the models the MSK
                               endpoint offers. --apply adds new models, removes
                               retired ones, refreshes token limits and the README.
                               --test sends a one-line prompt to every configured model.
  aiportal.py readme                Regenerate the model list in README.md
"""
import base64
import json
import os
import re
import secrets
import stat
import sys
import time

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
CONFIG_PATH = os.path.join(SCRIPT_DIR, "litellm_config.yaml")
AUTH_PATH = os.path.join(SCRIPT_DIR, ".auth.env")
README_PATH = os.path.join(SCRIPT_DIR, "README.md")
PROXY_KEY_PATH = os.path.join(SCRIPT_DIR, ".litellm_master_key")

WEBUI_URL = "https://chat.aicopilot.aws.mskcc.org"
API_BASE = f"{WEBUI_URL}/api/v1"

# Endpoint entries that are routers rather than models
EXCLUDED_ENDPOINT_IDS = {"msk-default"}

TOKEN_WARN_DAYS = 2

README_BEGIN = "<!-- BEGIN MODEL LIST (generated by ./aiportal.py readme) -->"
README_END = "<!-- END MODEL LIST -->"

TOKEN_HELP = f"""To get a new token:
  1. Visit {WEBUI_URL} and log in
  2. Open Developer Tools (F12) -> Application/Storage -> Cookies
  3. Copy the 'token' cookie value
  4. Update {AUTH_PATH}:
       export WEBUI_SESSION_TOKEN='<token>'"""


# --- config -----------------------------------------------------------------

def _yaml():
    from ruamel.yaml import YAML
    y = YAML()
    y.preserve_quotes = True
    y.width = 200
    y.indent(mapping=2, sequence=4, offset=2)
    return y


def load_config():
    with open(CONFIG_PATH) as f:
        return _yaml().load(f)


def _space_model_entries(text):
    """Put a blank line between model_list entries."""
    return re.sub(r"\n+(  - model_name:)", r"\n\n\1", text).replace("model_list:\n\n", "model_list:\n")


def _clear_comments(node):
    if hasattr(node, "ca"):
        node.ca.items.clear()
        node.ca.comment = None
    children = node.values() if isinstance(node, dict) else node if isinstance(node, list) else []
    for child in children:
        _clear_comments(child)


def save_config(config):
    # model_list carries no comments; clearing them stops blank separator lines
    # (which ruamel stores as comments) from drifting when keys are added
    _clear_comments(config["model_list"])
    with open(CONFIG_PATH, "w") as f:
        _yaml().dump(config, f, transform=_space_model_entries)


def backend_id(entry):
    """The model id on the MSK endpoint, e.g. bedrock/us.anthropic.claude-opus-5."""
    return entry["litellm_params"]["model"].removeprefix("openai/")


def visible_models(config):
    return [m for m in config["model_list"] if not m.get("model_info", {}).get("hidden")]


def group_of(name):
    if name.startswith("claude-"):
        return "Claude Models"
    if name.startswith(("gpt-", "o1", "o3", "o4")):
        return "OpenAI GPT Models (via Azure)"
    return "Other Models"


# --- token ------------------------------------------------------------------

def load_token():
    token = os.environ.get("WEBUI_SESSION_TOKEN")
    if not token and os.path.exists(AUTH_PATH):
        m = re.search(r"WEBUI_SESSION_TOKEN=['\"]?([^'\"\n]+)", open(AUTH_PATH).read())
        token = m and m.group(1)
    return token


def token_expiry(token):
    try:
        payload = token.split(".")[1]
        payload += "=" * (-len(payload) % 4)
        return json.loads(base64.urlsafe_b64decode(payload)).get("exp")
    except Exception:
        return None


def restrict_to_owner(path):
    """Make a secret file readable only by its owner; returns True if it had to be tightened."""
    mode = stat.S_IMODE(os.stat(path).st_mode)
    if mode & (stat.S_IRWXG | stat.S_IRWXO):
        os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)
        return True
    return False


def ensure_proxy_key():
    """The secret clients use to authenticate to the proxy, created on first use."""
    if not os.path.exists(PROXY_KEY_PATH):
        fd = os.open(PROXY_KEY_PATH, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write(f"sk-{secrets.token_urlsafe(32)}\n")
    restrict_to_owner(PROXY_KEY_PATH)
    return open(PROXY_KEY_PATH).read().strip()


def cmd_token_check():
    """Exit 0 if usable (possibly with a warning), 1 if missing or expired."""
    if os.path.exists(AUTH_PATH) and restrict_to_owner(AUTH_PATH):
        print(f"Note: {AUTH_PATH} was readable by other users; restricted it to you.")
    token = load_token()
    if not token:
        print(f"Error: WEBUI_SESSION_TOKEN not found in {AUTH_PATH}\n\n{TOKEN_HELP}")
        return 1
    exp = token_expiry(token)
    if exp is None:
        return 0
    remaining = exp - time.time()
    when = time.strftime("%Y-%m-%d %H:%M", time.localtime(exp))
    if remaining <= 0:
        print(f"Error: your MSK session token expired on {when}.\n\n{TOKEN_HELP}")
        return 1
    if remaining < TOKEN_WARN_DAYS * 86400:
        hours = round(remaining / 3600)
        print(f"Warning: your MSK session token expires in {hours}h ({when}).\n\n{TOKEN_HELP}\n")
    return 0


# --- endpoint ---------------------------------------------------------------

def _session():
    import requests
    import urllib3
    urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)
    s = requests.Session()
    s.verify = False
    s.headers["Authorization"] = f"Bearer {load_token()}"
    return s


def endpoint_models():
    """Real models on the endpoint, skipping assistant presets, pipes and routers."""
    r = _session().get(f"{API_BASE}/models", timeout=30)
    r.raise_for_status()
    models = {}
    for m in r.json()["data"]:
        info = m.get("info") or {}
        if "pipe" in m or info.get("base_model_id") or m["id"] in EXCLUDED_ENDPOINT_IDS:
            continue
        models[m["id"]] = m
    return models


def smoke_test(model_id):
    r = _session().post(
        f"{API_BASE}/chat/completions",
        json={
            "model": model_id,
            "messages": [{"role": "user", "content": "Reply with OK"}],
            "max_tokens": 1000,
            "chat_id": "",
        },
        timeout=180,
    )
    if r.ok:
        return True, ""
    return False, f"{r.status_code} {r.text[:120]}"


def friendly_name(endpoint_model):
    """'OpenAI GPT-5.6 Terra' -> 'gpt-5.6-terra', 'Claude Opus 5.5' -> 'claude-opus-5.5'."""
    name = re.sub(r"^OpenAI\s+", "", endpoint_model.get("name") or endpoint_model["id"])
    return re.sub(r"\s+", "-", name.strip()).lower()


def display_name(endpoint_model):
    return re.sub(r"^OpenAI\s+", "", endpoint_model.get("name") or endpoint_model["id"])


def new_entry(endpoint_model):
    from ruamel.yaml.comments import CommentedMap
    is_claude = "anthropic.claude" in endpoint_model["id"]
    params = CommentedMap(
        model=f"openai/{endpoint_model['id']}",
        api_base=API_BASE,
        api_key="os.environ/WEBUI_SESSION_TOKEN",
    )
    if is_claude:
        params["drop_params"] = True
        params["max_tokens"] = 16384
    info = CommentedMap(verify_ssl=False, display_name=display_name(endpoint_model))
    info["max_input_tokens"] = endpoint_model.get("max_input_tokens") or 128000
    info["max_output_tokens"] = endpoint_model.get("max_output_tokens") or 32768
    return CommentedMap(model_name=friendly_name(endpoint_model), litellm_params=params, model_info=info)


def remove_from_fallbacks(config, names):
    router = config.get("router_settings", {})
    for key in ("fallbacks", "content_policy_fallbacks"):
        rules = router.get(key) or []
        for rule in list(rules):
            (primary, targets), = rule.items()
            if primary in names:
                rules.remove(rule)
                continue
            for t in [t for t in targets if t in names]:
                targets.remove(t)
            if not targets:
                rules.remove(rule)


def cmd_sync(apply, test):
    config = load_config()
    live = endpoint_models()
    entries = config["model_list"]
    configured = {backend_id(m) for m in entries}

    added = [mid for mid in live if mid not in configured]
    retired = [m["model_name"] for m in entries if backend_id(m) not in live]
    changed_limits = []
    for entry in entries:
        mid = backend_id(entry)
        if mid not in live:
            continue
        info = entry.setdefault("model_info", {})
        for key in ("max_input_tokens", "max_output_tokens"):
            value = live[mid].get(key)
            if value and info.get(key) != value:
                changed_limits.append(f"{entry['model_name']}: {key} {info.get(key)} -> {value}")
                info[key] = value

    print(f"Endpoint offers {len(live)} models; config has {len(entries)} entries.")
    for mid in added:
        print(f"  + new:     {friendly_name(live[mid])}  ({mid})")
    for name in retired:
        print(f"  - retired: {name}")
    for line in changed_limits:
        print(f"  ~ limits:  {line}")
    if not (added or retired or changed_limits):
        print("  Config is up to date.")

    if apply and (added or retired or changed_limits):
        for name in retired:
            config["model_list"] = [m for m in config["model_list"] if m["model_name"] != name]
        remove_from_fallbacks(config, set(retired))
        for mid in added:
            config["model_list"].append(new_entry(live[mid]))
        save_config(config)
        write_readme(config)
        print(f"\nUpdated {CONFIG_PATH} and {README_PATH}.")
        print("The proxy restarts automatically on your next aiportal-opencode / aiportal-claude launch.")
        if retired:
            print("If a retired model was a script's DEFAULT_MODEL, update it in connect_opencode.sh / connect_claude.sh.")
    elif added or retired or changed_limits:
        print("\nRun with --apply to update the config.")

    if test:
        print("\nTesting configured models against the endpoint:")
        failed = 0
        for entry in load_config()["model_list"] if apply else config["model_list"]:
            if entry.get("model_info", {}).get("hidden"):
                continue
            ok, err = smoke_test(backend_id(entry))
            failed += not ok
            print(f"  {'OK  ' if ok else 'FAIL'} {entry['model_name']}  {err}")
        return 1 if failed else 0
    return 0


# --- generated outputs --------------------------------------------------------

def cmd_names():
    for m in visible_models(load_config()):
        print(m["model_name"])


def cmd_opencode_models():
    models = {}
    for m in visible_models(load_config()):
        info = m.get("model_info", {})
        entry = {
            "name": info.get("display_name", m["model_name"]),
            "tool_call": info.get("supports_function_calling", True),
            "attachment": info.get("supports_vision", True),
        }
        if info.get("max_input_tokens") and info.get("max_output_tokens"):
            entry["limit"] = {"context": info["max_input_tokens"], "output": info["max_output_tokens"]}
        models[m["model_name"]] = entry
    print(json.dumps(models))


def readme_section(config):
    lines = []
    groups = {}
    for m in visible_models(config):
        groups.setdefault(group_of(m["model_name"]), []).append(m)
    for group in ("Claude Models", "OpenAI GPT Models (via Azure)", "Other Models"):
        if group not in groups:
            continue
        lines.append(f"**{group}:**")
        for m in groups[group]:
            info = m.get("model_info", {})
            ctx = info.get("max_input_tokens")
            out = info.get("max_output_tokens")
            limits = f" - {ctx:,} context / {out:,} max output" if ctx and out else ""
            lines.append(f"- `{m['model_name']}` - {info.get('display_name', m['model_name'])}{limits}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_readme(config):
    text = open(README_PATH).read()
    if README_BEGIN not in text:
        return
    start = text.index(README_BEGIN) + len(README_BEGIN)
    end = text.index(README_END)
    text = text[:start] + "\n" + readme_section(config) + text[end:]
    with open(README_PATH, "w") as f:
        f.write(text)


def main(argv):
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    cmd, args = argv[0], argv[1:]
    if cmd == "names":
        cmd_names()
    elif cmd == "opencode-models":
        cmd_opencode_models()
    elif cmd == "token-check":
        return cmd_token_check()
    elif cmd == "proxy-key":
        print(ensure_proxy_key())
    elif cmd == "sync":
        return cmd_sync(apply="--apply" in args, test="--test" in args)
    elif cmd == "readme":
        write_readme(load_config())
    else:
        print(f"Unknown command: {cmd}\n{__doc__}")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
